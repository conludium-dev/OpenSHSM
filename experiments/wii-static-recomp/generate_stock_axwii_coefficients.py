"""Reproduce Dolphin's free DSP coefficient replacement without NumPy or a ROM dump.

Reference: dolphin-emu/dolphin e2ad09306e6d371f7272205bdc363da9fe05fe08,
docs/DSP/free_dsp_rom/generate_coefs.py (stgn/ligfx).
This is a PC filter approximation, not Nintendo's original DSP DROM.
"""
# SPDX-License-Identifier: GPL-2.0-or-later
from pathlib import Path
import argparse
import hashlib
import math
import struct


EXPECTED_SHA256 = 'd7741279c2e8ec5c5fb318f8fbdd6de6bf583520d288e836a5383233a4238179'


def i0(value):
    total = term = 1.0
    for index in range(1, 100):
        term *= (value / (2 * index)) ** 2
        total += term
        if term < total * 1e-17:
            return total
    raise ValueError('Bessel series did not converge')


def coefficients():
    result = []
    beta = math.pi * 9 / 4
    for cutoff, kaiser in ((0.5, False), (0.75, True), (1.0, False)):
        samples = []
        for index in range(512):
            x = -2 + index * (4 / 511)
            window = i0(beta * math.sqrt(1 - ((index - 255.5) / 255.5) ** 2)) / i0(beta) \
                if kaiser else 0.54 - 0.46 * math.cos(2 * math.pi * index / 511)
            value = math.pi * x * cutoff
            samples.append((math.sin(value) / value if value else 1) * window)
        phases = [[samples[tap * 128 + 127 - phase] for tap in range(4)] for phase in range(128)]
        maximum = max(sum(phase) for phase in phases)
        result.extend(round(value / maximum * 32767) & 0xffff for phase in phases for value in phase)
    result.extend([0] * 512)
    # Preserve the published free replacement's GBA compatibility entries.
    for address, value in ((0x03b, 0x0065), (0x043, 0x0076), (0x0ca, 0x3461),
            (0x0e2, 0x376f), (0x1b8, 0x007f), (0x1f8, 0x0009), (0x1fc, 0x0003),
            (0x229, 0x657c), (0x231, 0x64fc), (0x259, 0x6143), (0x285, 0x5aff),
            (0x456, 0x102f), (0x468, 0xf808), (0x491, 0x6a0f), (0x5f1, 0x0200),
            (0x5f6, 0x7f65), (0x65b, 0x0000), (0x66b, 0x0000), (0x66c, 0x06f2),
            (0x6fe, 0x0008), (0x723, 0xffe0), (0x766, 0x0273)):
        result[address] = value
    data = struct.pack('>2048H', *result)
    if hashlib.sha256(data).hexdigest() != EXPECTED_SHA256:
        raise ValueError('Generated coefficients differ from pinned free Dolphin replacement')
    return struct.unpack('>2048h', data)


def header():
    values = coefficients()
    lines = ['// Copyright 2015 stgn; 2017 ligfx; Dolphin Emulator Project',
        '// SPDX-License-Identifier: GPL-2.0-or-later',
        '// Generated by generate_stock_axwii_coefficients.py; free PC approximation, not original DROM.',
        '#pragma once', '#include <array>', '#include <cstdint>', '',
        'namespace openshsm::experiment {', '',
        'inline constexpr std::array<int16_t, 2048> axwii_free_coefficients = {']
    lines.extend('    ' + ', '.join(map(str, values[index:index + 16])) + ',' for index in range(0, 2048, 16))
    return '\n'.join([*lines, '};', '', '}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = Path(__file__).with_name('stock_axwii_coefficients.h')
    content = header()
    if args.check:
        if path.read_text() != content:
            raise ValueError('Committed coefficient header differs')
    else:
        path.write_text(content)
    print('FREE_AXWII_COEFFICIENTS_PINNED_PASS', EXPECTED_SHA256)


if __name__ == '__main__':
    main()
