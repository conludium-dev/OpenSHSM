"""Run whole original SCInit and repeated SCCheckStatus after pending STM/ES CLOSE."""
from pathlib import Path
import hashlib
import json

parent = Path('experiments/wii-static-recomp/build_es_close_dolphin.py')
body = parent.read_text().replace('dolphin-es-close', 'dolphin-sysconf').replace(
    'run_es_close_disc_dolphin.ps1', 'run_sysconf_disc_dolphin.ps1')
old = '0x802497f0 if index in (7, 8, 11, 13, 15) else 0x80242740 if index in (9, 12) else 0x80249790 if index in (10, 14) else'
assert body.count(old) == 1
body = body.replace(old, '0x80247450 if index == 8 else 0x802474f0 if index >= 9 else 0x802497f0 if index == 7 else')
snapshot = '''        if index >= 8:
            for slot, address in [(704, 0x8052b008), (705, 0x8052b01c), (706, 0x8052b01e)]:
                pointer(code, 11, address)
                code.extend([dform(34, 0, 11, 0), dform(38, 0, 30, slot)])
            for slot, address in [(648, 0x8052aa70), (708, 0x804b31a0), (712, 0x804b31a4),
                (716, 0x804b719c), (720, 0x804b3160), (724, 0x804b317c), (728, 0x804b3180),
                (732, 0x804b3158)]:
                pointer(code, 11, address)
                code.extend([dform(32, 0, 11, 0), dform(36, 0, 30, slot)])
'''
marker = "exec(compile(body, str(parent), 'exec'), {'__file__': __file__})"
assert body.count(marker) == 1
extension = "body = body.replace('    literal = ast.get_source_segment(body, node.value)', " + repr(
    "    if name == 'capture':\n        value += " + repr(snapshot) + "\n    literal = ast.get_source_segment(body, node.value)") + ")\n"
body = body.replace(marker, extension + marker)
exec(compile(body, str(parent), 'exec'), {'__file__': __file__})
path = Path('work/private-game/static-recomp/dolphin-sysconf/generation.json')
report = json.loads(path.read_text())
report['sysconfParentSha256'] = hashlib.sha256(parent.read_bytes()).hexdigest()
for case in report['records']:
    index = case['index']
    if index >= 8:
        case['kind'] = 'SCInit' if index == 8 else 'SCCheckStatus'
report['limits'] = ['Whole original SCInit/SCCheckStatus after original STM pending, FS/ES/title/directory and one CLOSE.',
    'Prepared thread/heap/entry; boot-profile pointer/status captured, no forced SC flags, FD, callback result or file data.',
    'Console settings generated by isolated Dolphin laboratory user directory are NOT original disc assets or physical Wii NAND; no game assets published.']
path.write_text(json.dumps(report, indent=2) + '\n')
