"""Generate an embedded, antialiased monospace atlas from the bundled OFL font."""
from pathlib import Path
import hashlib
import json
import math
from PIL import Image, ImageDraw, ImageFont
import PIL


def main():
    public = Path(__file__).resolve().parent
    font_path = public / 'assets/debug-font/JetBrainsMono-Bold.ttf'
    font = ImageFont.truetype(str(font_path), 18)
    ascent, descent = font.getmetrics()
    advance = math.ceil(font.getlength('M'))
    assert all(abs(font.getlength(chr(code)) - font.getlength('M')) < 0.01 for code in range(32, 127))
    cell_width, cell_height = advance + 4, ascent + descent + 2
    width, height = cell_width * 16, cell_height * 6
    atlas = Image.new('L', (width, height))
    draw = ImageDraw.Draw(atlas)
    for code in range(32, 127):
        index = code - 32
        draw.text(((index % 16) * cell_width + 2, (index // 16) * cell_height + ascent),
            chr(code), font=font, fill=255, anchor='ls')
    pixels = atlas.tobytes()
    encoded = []
    index = 0
    while index < len(pixels):
        end = index + 1
        while end < len(pixels) and pixels[end] == pixels[index] and end - index < 255:
            end += 1
        encoded.append(((end - index) << 8) | pixels[index])
        index = end
    assert bytes(value & 255 for value in encoded for _ in range(value >> 8)) == pixels
    header = public / 'stock_debug_font.h'
    header.write_text('// JetBrains Mono Bold, copyright JetBrains Mono Project Authors; SIL OFL-1.1.\n'
        '// Generated by prepare_stock_debug_font.py; license: assets/debug-font/OFL.txt.\n'
        '#pragma once\n#include <cstdint>\n#include <vector>\n'
        'namespace openshsm::experiment {\n'
        f'inline constexpr int debug_font_width = {width}, debug_font_height = {height};\n'
        f'inline constexpr int debug_font_cell_width = {cell_width}, debug_font_cell_height = {cell_height};\n'
        f'inline constexpr int debug_font_advance = {advance};\n'
        'inline std::vector<uint8_t> debug_font_pixels() {\n'
        '    constexpr uint16_t runs[] = {\n' + ''.join(
            '        ' + ', '.join(f'0x{value:04x}' for value in encoded[start:start + 12]) + ',\n'
            for start in range(0, len(encoded), 12)) +
        '    };\n    std::vector<uint8_t> pixels;\n'
        '    pixels.reserve(debug_font_width * debug_font_height);\n'
        '    for (uint16_t run : runs) {\n'
        '        pixels.insert(pixels.end(), run >> 8, static_cast<uint8_t>(run));\n'
        '    }\n    return pixels;\n}\n}\n')
    report = {'font': font.getname(), 'size': 18, 'Pillow': PIL.__version__,
        'fontSha256': hashlib.sha256(font_path.read_bytes()).hexdigest(),
        'pixelsSha256': hashlib.sha256(pixels).hexdigest(),
        'headerSha256': hashlib.sha256(header.read_bytes()).hexdigest(),
        'width': width, 'height': height, 'advance': advance, 'runs': len(encoded)}
    (public / 'assets/debug-font/atlas.json').write_text(json.dumps(report, indent=2) + '\n')
    print('MONOSPACE_ANTIALIASED_FONT_ATLAS_GENERATED', report, flush=True)


if __name__ == '__main__':
    main()
